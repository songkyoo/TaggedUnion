using System.Text;

using static Macaron.Union.TaggedUnionGeneratedMemberNames;

namespace Macaron.Union;

internal sealed class TaggedUnionMemoryPackSerializerSourceWriter(
    TaggedUnionMemoryPackSerializerGenerationModel model
)
{
    #region Constants
    private const string Indent = "    ";
    #endregion

    #region Fields
    private readonly StringBuilder _builder = new();
    private string _leadingWhitespace = "";
    #endregion

    #region Methods
    public string Generate()
    {
        AppendLine("// <auto-generated />");
        AppendLine("#nullable enable");
        AppendLine("#pragma warning disable CS9074");
        AppendLine();

        var hasNamespace = model.Namespace.Length > 0;

        if (hasNamespace)
        {
            AppendLine($"namespace {model.Namespace}");
            AppendLine("{");

            IncreaseIndent();
        }

        foreach (var typeString in model.ContainingTypes)
        {
            AppendLine(typeString);
            AppendLine("{");

            IncreaseIndent();
        }

        var unionTypeName = model.TypeName;

        AppendLine($"readonly partial struct {unionTypeName} : global::MemoryPack.IMemoryPackable<{unionTypeName}>");
        AppendLine("{");

        IncreaseIndent();

        WriteStaticConstructor();
        AppendLine();
        WriteRegisterFormatterMethod();
        AppendLine();
        WriteSerializeMethod();
        AppendLine();
        WriteDeserializeMethod();
        AppendLine();
        WriteLegacyFormatter();

        DecreaseIndent();

        AppendLine("}");

        for (var i = 0; i < model.ContainingTypes.Length; ++i)
        {
            DecreaseIndent();

            AppendLine("}");
        }

        if (hasNamespace)
        {
            DecreaseIndent();

            AppendLine("}");
        }

        return _builder.ToString();
    }

    private void WriteDeserializeMethod()
    {
        var unionTypeName = model.TypeName;

        AppendLine("[global::MemoryPack.Internal.Preserve]");
        AppendLine("#if NET7_0_OR_GREATER");
        AppendLine($"static void global::MemoryPack.IMemoryPackable<{unionTypeName}>.Deserialize(");
        AppendLine("#else");
        AppendLine("public static void Deserialize(");
        AppendLine("#endif");
        AppendLine($"{Indent}ref global::MemoryPack.MemoryPackReader reader,");
        AppendLine($"{Indent}scoped ref {unionTypeName} value");
        AppendLine(")");
        AppendLine("{");
        AppendLine($"{Indent}if (!reader.TryReadUnionHeader(out var tag))");
        AppendLine($"{Indent}{{");
        AppendLine($"{Indent}{Indent}value = default;");
        AppendLine();
        AppendLine($"{Indent}{Indent}return;");
        AppendLine($"{Indent}}}");
        AppendLine();
        AppendLine($"{Indent}switch (tag)");
        AppendLine($"{Indent}{{");

        foreach (var caseModel in model.Cases)
        {
            AppendLine($"{Indent}{Indent}case {caseModel.Tag}: value = new {unionTypeName}({GetReadExpression(caseModel)}); break;");
        }

        AppendLine($"{Indent}{Indent}default:");
        AppendLine($"{Indent}{Indent}{Indent}global::MemoryPack.MemoryPackSerializationException.ThrowInvalidTag(tag, typeof({unionTypeName}));");
        AppendLine($"{Indent}{Indent}{Indent}break;");
        AppendLine($"{Indent}}}");
        AppendLine("}");
    }

    private void WriteLegacyFormatter()
    {
        var unionTypeName = model.TypeName;

        AppendLine("#if !NET7_0_OR_GREATER");
        AppendLine("[global::MemoryPack.Internal.Preserve]");
        AppendLine($"private sealed class MemoryPackFormatter : global::MemoryPack.MemoryPackFormatter<{unionTypeName}>");
        AppendLine("{");
        AppendLine($"{Indent}[global::MemoryPack.Internal.Preserve]");
        AppendLine($"{Indent}public override void Serialize<TBufferWriter>(");
        AppendLine($"{Indent}{Indent}ref global::MemoryPack.MemoryPackWriter<TBufferWriter> writer,");
        AppendLine($"{Indent}{Indent}scoped ref {unionTypeName} value");
        AppendLine($"{Indent})");
        AppendLine($"{Indent}{{");
        AppendLine($"{Indent}{Indent}{unionTypeName}.Serialize(ref writer, ref value);");
        AppendLine($"{Indent}}}");
        AppendLine();
        AppendLine($"{Indent}[global::MemoryPack.Internal.Preserve]");
        AppendLine($"{Indent}public override void Deserialize(");
        AppendLine($"{Indent}{Indent}ref global::MemoryPack.MemoryPackReader reader,");
        AppendLine($"{Indent}{Indent}scoped ref {unionTypeName} value");
        AppendLine($"{Indent})");
        AppendLine($"{Indent}{{");
        AppendLine($"{Indent}{Indent}{unionTypeName}.Deserialize(ref reader, ref value);");
        AppendLine($"{Indent}}}");
        AppendLine("}");
        AppendLine("#endif");
    }

    private void WriteRegisterFormatterMethod()
    {
        var unionTypeName = model.TypeName;

        AppendLine("[global::MemoryPack.Internal.Preserve]");
        AppendLine("#if NET7_0_OR_GREATER");
        AppendLine("static void global::MemoryPack.IMemoryPackFormatterRegister.RegisterFormatter()");
        AppendLine("#else");
        AppendLine("public static void RegisterFormatter()");
        AppendLine("#endif");
        AppendLine("{");
        AppendLine($"{Indent}if (!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<{unionTypeName}>())");
        AppendLine($"{Indent}{{");
        AppendLine("#if NET7_0_OR_GREATER");
        AppendLine($"{Indent}{Indent}global::MemoryPack.MemoryPackFormatterProvider.Register(new global::MemoryPack.Formatters.MemoryPackableFormatter<{unionTypeName}>());");
        AppendLine("#else");
        AppendLine($"{Indent}{Indent}global::MemoryPack.MemoryPackFormatterProvider.Register(new MemoryPackFormatter());");
        AppendLine("#endif");
        AppendLine($"{Indent}}}");
        AppendLine();
        AppendLine($"{Indent}if (!global::MemoryPack.MemoryPackFormatterProvider.IsRegistered<{unionTypeName}[]>())");
        AppendLine($"{Indent}{{");
        AppendLine($"{Indent}{Indent}global::MemoryPack.MemoryPackFormatterProvider.Register(new global::MemoryPack.Formatters.ArrayFormatter<{unionTypeName}>());");
        AppendLine($"{Indent}}}");
        AppendLine("}");
    }

    private void WriteSerializeMethod()
    {
        var unionTypeName = model.TypeName;
        var tagFieldAccess = $"value.{TagField}";

        AppendLine("[global::MemoryPack.Internal.Preserve]");
        AppendLine("#if NET7_0_OR_GREATER");
        AppendLine($"static void global::MemoryPack.IMemoryPackable<{unionTypeName}>.Serialize<TBufferWriter>(");
        AppendLine("#else");
        AppendLine("public static void Serialize<TBufferWriter>(");
        AppendLine("#endif");
        AppendLine($"{Indent}ref global::MemoryPack.MemoryPackWriter<TBufferWriter> writer,");
        AppendLine($"{Indent}scoped ref {unionTypeName} value");
        AppendLine(")");
        AppendLine("#if !NET7_0_OR_GREATER");
        AppendLine($"{Indent}where TBufferWriter : class, global::System.Buffers.IBufferWriter<byte>");
        AppendLine("#endif");
        AppendLine("{");
        AppendLine($"{Indent}if ({tagFieldAccess} == 0)");
        AppendLine($"{Indent}{{");
        AppendLine($"{Indent}{Indent}writer.WriteNullUnionHeader();");
        AppendLine();
        AppendLine($"{Indent}{Indent}return;");
        AppendLine($"{Indent}}}");
        AppendLine();
        AppendLine($"{Indent}writer.WriteUnionHeader({tagFieldAccess});");
        AppendLine();
        AppendLine($"{Indent}switch ({tagFieldAccess})");
        AppendLine($"{Indent}{{");

        foreach (var caseModel in model.Cases)
        {
            var methodName = caseModel.IsMemoryPackable ? "WritePackable" : "WriteValue";
            var valuePropertyName = GetValueProperty(caseModel.Tag);

            AppendLine($"{Indent}{Indent}case {caseModel.Tag}: writer.{methodName}(value.{valuePropertyName}); break;");
        }

        AppendLine($"{Indent}{Indent}default:");
        AppendLine($"{Indent}{Indent}{Indent}global::MemoryPack.MemoryPackSerializationException.ThrowInvalidTag({tagFieldAccess}, typeof({unionTypeName}));");
        AppendLine($"{Indent}{Indent}{Indent}break;");
        AppendLine($"{Indent}}}");
        AppendLine("}");
    }

    private void WriteStaticConstructor()
    {
        var unionTypeName = model.TypeName;

        AppendLine("static partial void StaticConstructor();");
        AppendLine();
        AppendLine($"static {unionTypeName}()");
        AppendLine("{");
        AppendLine("#if NET7_0_OR_GREATER");
        AppendLine($"{Indent}global::MemoryPack.MemoryPackFormatterProvider.Register<{unionTypeName}>();");
        AppendLine("#else");
        AppendLine($"{Indent}RegisterFormatter();");
        AppendLine("#endif");
        AppendLine($"{Indent}StaticConstructor();");
        AppendLine("}");
    }

    private void AppendLine(string text = "")
    {
        if (text.Length > 0)
        {
            _builder.Append(_leadingWhitespace);
            _builder.AppendLine(text);
        }
        else
        {
            _builder.AppendLine("");
        }
    }

    private void DecreaseIndent()
    {
        _leadingWhitespace = _leadingWhitespace[..^Indent.Length];
    }

    private static string GetReadExpression(MemoryPackUnionCaseGenerationModel caseModel)
    {
        var methodName = caseModel.IsMemoryPackable ? "ReadPackable" : "ReadValue";
        var expression = $"reader.{methodName}<{caseModel.FullyQualifiedTypeName}>()";

        return caseModel.IsReferenceType
            ? $"{expression} ?? throw new global::MemoryPack.MemoryPackSerializationException(\"The value for tag {caseModel.Tag} cannot be null.\")"
            : expression;
    }

    private void IncreaseIndent()
    {
        _leadingWhitespace += Indent;
    }
    #endregion
}
